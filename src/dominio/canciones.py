def eleccion_opciones():

    while True:

        eleccion = int(input("\nIngrese la opción deseada: "))

        if eleccion < 0 or eleccion > 3:
            print("- - - - -"*4)
            print("\nOpción inválida. Por favor, ingrese un número entre 1 y 3.\n")
            print("- - - - -"*4)
            continue

        if eleccion == 1:
            print("Nuestras canciones disponibles son: \n")
            print(" ")
            for c in canciones:
                print(f"\n{c['id']}: '{c['titulo']}', de {c['artista']}\n")
                print(" - - - "*10)

        if eleccion == 2:
            num_cancion = int(input(
                f"Dentro de nuestras {len(canciones)} canciones, ingrese el número de la canción que le gustaría ver: "))

            if num_cancion < 1 or num_cancion > len(canciones):
                print("- - - - -"*4)
                print(
                    f"\nOpción inválida. Por favor, ingrese un número entre 1 y {len(canciones)}.\n")
                print("- - - - -"*4)
                continue

            print("\nLa información que poseemos de su canción elegida es: \n")
            print(f"Título: {canciones[num_cancion-1]['titulo']}")
            print(f"Artista: {canciones[num_cancion-1]['artista']}")
            print(f"Álbum: {canciones[num_cancion-1]['album']}")
            print(f"Género: {canciones[num_cancion-1]['genero']}")
            print(f"Año: {canciones[num_cancion-1]['anio']}")
            print(
                f"Duración (segundos): {canciones[num_cancion-1]['duracion_seg']}")

        if eleccion == 3:
            print(" ")
            print("- - - - - "*6)
            print("\nMuchas gracias por ver nuestro catálogo musical. Nos vemos!\n")
            print("- - - - - "*6)
            break
